const path=require('node:path');
const os=require('node:os');
const {pathToFileURL}=require('node:url');
const skillDir=process.env.TEARDOWN_SKILL_DIR || path.join(os.homedir(),'.agents/skills/teardown');
const {chromium}=require(path.join(skillDir,'node_modules/playwright'));
const output=process.env.TEARDOWN_TEST_OUTPUT || path.join(os.tmpdir(),'teardown-evaluation');
const fs=require('node:fs');
(async()=>{
 fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--enable-webgl','--ignore-gpu-blocklist','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
 const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.route(/^https?:\/\//,route=>{requests.push(route.request().url());return route.abort()});
 await page.goto(pathToFileURL(path.join(__dirname,'demo.html')).href);
 await page.waitForFunction(()=>window.SIM?.ready,null,{timeout:60000});
 await page.click('#tour');
 await page.click('[data-view="hero"]');
 await page.screenshot({path:path.join(output,'desktop.png')});
 console.log('Ready',await page.evaluate(()=>window.VIEWER.getState()));
 const before=await page.evaluate(()=>window.VIEWER.getState().camera);
 await page.mouse.move(740,420);await page.mouse.down();await page.mouse.move(840,470,{steps:8});await page.mouse.up();
 await page.waitForFunction(previous=>window.VIEWER.getState().camera.some((v,i)=>Math.abs(v-previous[i])>.05),before);
 const distance=await page.evaluate(()=>Math.hypot(...window.VIEWER.getState().camera));
 await page.mouse.wheel(0,160);
 await page.waitForFunction(previous=>Math.abs(Math.hypot(...window.VIEWER.getState().camera)-previous)>.05,distance);
 await page.click('[data-view="side"]');
 if(await page.getAttribute('[data-view="side"]','aria-pressed')!=='true')throw Error('Side view failed');
 await page.screenshot({path:path.join(output,'side.png')});
 await page.click('[data-finish="graphite"]');
 if((await page.evaluate(()=>window.VIEWER.getState())).finish!=='graphite')throw Error('Finish failed');
 await page.click('[data-view="rear"]');
 await page.screenshot({path:path.join(output,'graphite.png')});
 await page.click('#tour');
 if(!(await page.evaluate(()=>window.VIEWER.getState())).auto)throw Error('Auto tour failed');
 await page.click('[data-view="top"]');
 await page.screenshot({path:path.join(output,'top.png')});
 await page.click('#details');
 await page.click('[data-detail="grip"]');
 if(!await page.locator('#detail-card').isVisible())throw Error('Detail card failed');
 if(!(await page.locator('#detail-title').textContent()).includes('Bề mặt tay cầm'))throw Error('Wrong detail');
 await page.screenshot({path:path.join(output,'details.png')});
 await page.click('#detail-close');
 await page.click('#fullscreen');
 await page.waitForFunction(()=>!!document.fullscreenElement);
 await page.click('#fullscreen');
 await page.waitForFunction(()=>!document.fullscreenElement);
 await page.selectOption('#quality','low');
 if(!(await page.evaluate(()=>window.VIEWER.getState())).lowQuality)throw Error('Quality toggle failed');
 const downloadPromise=page.waitForEvent('download');
 await page.click('#export');
 const download=await downloadPromise;
 const filename=path.join(output,'export.png');await download.saveAs(filename);
 if(fs.readFileSync(filename).subarray(1,4).toString()!=='PNG')throw Error('PNG export invalid');
 await page.click('#reset');
 if((await page.evaluate(()=>window.VIEWER.getState())).finish!=='silver')throw Error('Reset did not restore finish');
 if((await page.evaluate(()=>window.VIEWER.getState())).lowQuality)throw Error('Reset quality failed');
 await page.setViewportSize({width:390,height:844});
 await page.click('[data-finish="silver"]');await page.click('[data-view="hero"]');
 await page.screenshot({path:path.join(output,'mobile.png')});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 const stats=await page.evaluate(()=>{const gl=document.querySelector('canvas').getContext('webgl2');const ext=gl.getExtension('WEBGL_debug_renderer_info');return {renderer:ext?gl.getParameter(ext.UNMASKED_RENDERER_WEBGL):'unknown',title:document.title,ready:window.SIM.ready}});
 const result={errors,externalRequests:requests,overflow,...stats};fs.writeFileSync(path.join(output,'result.json'),JSON.stringify(result,null,2));console.log(result);
 await page.emulateMedia({reducedMotion:'reduce'});await page.reload();
 await page.waitForFunction(()=>window.SIM?.ready,null,{timeout:60000});
 if((await page.evaluate(()=>window.VIEWER.getState())).auto)throw Error('Reduced motion preference ignored');
 await browser.close();
 if(errors.length||requests.length||overflow)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
